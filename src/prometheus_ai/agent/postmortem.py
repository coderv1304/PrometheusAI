"""Deterministic postmortem rendering.

The postmortem is assembled from recorded state, not re-generated by a model:
timeline, evidence, decision, verification and follow-ups must match the audit
log exactly.

Wording rule from the BRD: these are *injected faults in a demo cluster*, not
production incidents.
"""

from __future__ import annotations

from prometheus_ai.models import Incident
from prometheus_ai.util import iso

_FOLLOW_UPS: dict[str, list[str]] = {
    "crashloop": [
        "Add a start-up probe that fails fast and surfaces the crash reason in the alert.",
        "Check whether the crash is data-dependent; restart is containment, not a root fix.",
    ],
    "oom": [
        "Right-size the memory request/limit from measured working-set p99.",
        "Add a memory-growth alert so the next leak is caught before OOMKill.",
    ],
    "bad_image": [
        "Pin images by digest and gate promotion on a smoke test.",
        "Add an admission or CI check that rejects non-existent image tags.",
    ],
    "latency": [
        "Find the saturated dependency; horizontal scaling only buys time.",
        "Add a latency SLO burn-rate alert to replace the static threshold.",
    ],
    "broken_config": [
        "Add schema validation for config in CI before rollout.",
        "Automate config rollback as a separately approved action.",
    ],
    "unknown": [
        "Broaden evidence collection and record the missing signal as a runbook gap.",
    ],
}


def render_postmortem(incident: Incident, audit: list) -> str:
    hyp = incident.hypothesis
    proposal = incident.proposal
    decision = incident.policy_decision
    execution = incident.execution
    verification = incident.verification
    root = hyp.category.value if hyp else "unknown"

    lines = [
        f"# Incident {incident.id}: {incident.alertname}",
        "",
        f"- **Status:** {incident.status}",
        f"- **Severity:** {incident.severity}",
        f"- **Service:** `{incident.namespace}/{incident.service}`",
        f"- **Started:** {iso(incident.started_at)}",
        f"- **Resolved:** {iso(incident.resolved_at) if incident.resolved_at else 'not resolved'}",
        f"- **Model backend:** `{incident.model_backend}`"
        + (" (synthetic demo mode)" if incident.model_backend == "demo-deterministic" else ""),
        f"- **Tool calls:** {incident.tool_calls}",
        f"- **Tokens:** {incident.tokens_in} in / {incident.tokens_out} out"
        f" (~${incident.cost_usd:.4f})",
        "",
        "> Scope note: this incident was **injected in a demo cluster**. It is not evidence "
        "of production incident handling.",
        "",
        "## Impact",
        "",
        f"{incident.summary or 'Alert fired for the demo service.'} "
        "Impact is limited to the demo namespace.",
        "",
        "## Timeline",
        "",
        "| Time | Actor | Node | Action | Decision |",
        "| --- | --- | --- | --- | --- |",
    ]
    for event in audit:
        lines.append(
            f"| {iso(event.ts)} | {event.actor} | {event.node} | "
            f"{event.action or '-'} | {event.decision or '-'} |"
        )

    lines += ["", "## Evidence", ""]
    if incident.evidence:
        lines.append("| Source | Query | Summary | Trust |")
        lines.append("| --- | --- | --- | --- |")
        for ev in incident.evidence:
            query = ev.query.replace("|", "\\|")[:80]
            summary = ev.summary.replace("|", "\\|")[:120]
            lines.append(
                f"| {ev.source} | `{query}` | {summary} | "
                f"{'untrusted' if ev.untrusted else 'trusted'} |"
            )
    else:
        lines.append("_No evidence was collected._")

    lines += ["", "## Root cause", ""]
    if hyp:
        lines.append(f"**Category:** `{hyp.category}` (confidence {hyp.confidence:.2f})")
        lines.append("")
        lines.append(hyp.reasoning)
    else:
        lines.append("No hypothesis was produced before escalation.")

    lines += ["", "## Proposed remediation", ""]
    if proposal:
        lines += [
            f"- **Action:** `{proposal.action}` on `{proposal.namespace}/{proposal.target_name}`",
            f"- **Parameters:** `{proposal.parameters}`",
            f"- **Action hash:** `{proposal.action_hash}`",
            f"- **Confidence:** {proposal.confidence:.2f}",
            f"- **Rationale:** {proposal.rationale}",
            f"- **Rollback plan:** {proposal.rollback}",
        ]
    else:
        lines.append("No remediation was proposed.")

    lines += ["", "## Approval and policy", ""]
    if incident.approval:
        lines.append(
            f"- **Human decision:** `{incident.approval.decision}` by "
            f"`{incident.approval.approver}` at {iso(incident.approval.created_at)}"
        )
        if incident.approval.reason:
            lines.append(f"- **Reason:** {incident.approval.reason}")
    else:
        lines.append("- No approval record exists. No write was permitted.")
    if decision:
        lines.append(f"- **Policy:** `{decision.code}` — {decision.reason}")
        for check in decision.checks:
            mark = "PASS" if check.passed else "FAIL"
            lines.append(f"  - `{mark}` {check.name}: {check.detail}")
    else:
        lines.append("- The policy engine was not reached.")

    lines += ["", "## Execution and verification", ""]
    if execution:
        lines.append(f"- **Execution status:** `{execution.status}` (dry run: `{bool(execution.command and '--dry-run=server' in execution.command)}`)")
        lines.append(f"- **Idempotency key:** `{execution.idempotency_key}`")
        if execution.command:
            lines.append(f"- **Command:** `{' '.join(execution.command)}`")
    else:
        lines.append("- No action was executed.")
    if verification:
        lines.append(f"- **Verification:** {'passed' if verification.success else 'failed'} — {verification.summary}")
        for check in verification.checks:
            lines.append(f"  - `{'PASS' if check.passed else 'FAIL'}` {check.name}: {check.detail}")
    else:
        lines.append("- No verification was run.")

    lines += ["", "## Follow-ups", ""]
    for item in _FOLLOW_UPS.get(root, _FOLLOW_UPS["unknown"]):
        lines.append(f"- [ ] {item}")
    lines.append("- [ ] Re-run the scenario in the eval harness and record the result.")

    lines += [
        "",
        "## What this postmortem does not prove",
        "",
        "The remediation was chosen from a deliberately narrow allowlist. Success here "
        "means the alert cleared for this injected fault, not that the service is "
        "healthy under production load.",
        "",
    ]
    return "\n".join(lines)
