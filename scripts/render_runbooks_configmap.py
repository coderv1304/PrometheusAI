"""Render docs/runbooks/*.md into the ConfigMap mounted by the agent.

Run after adding or editing a runbook:

    python scripts/render_runbooks_configmap.py

The output is committed so a plain `kubectl apply -k deploy/k8s/base` works
without kustomize file-loading flags. `tests/test_manifests.py` verifies the
ConfigMap is in sync.
"""

from __future__ import annotations

from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
RUNBOOKS = ROOT / "docs" / "runbooks"
OUTPUT = ROOT / "deploy" / "k8s" / "base" / "08-runbooks.yaml"


class _Literal(str):
    pass


def _literal_representer(dumper: yaml.SafeDumper, value: _Literal):
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style="|")


def render() -> str:
    yaml.SafeDumper.add_representer(_Literal, _literal_representer)
    data = {
        path.name: _Literal(path.read_text(encoding="utf-8"))
        for path in sorted(RUNBOOKS.glob("*.md"))
    }
    document = {
        "apiVersion": "v1",
        "kind": "ConfigMap",
        "metadata": {
            "name": "runbooks",
            "namespace": "prometheus-ai",
            "labels": {"app.kubernetes.io/part-of": "prometheus-ai"},
        },
        "data": data,
    }
    header = (
        "# Generated by scripts/render_runbooks_configmap.py from docs/runbooks/.\n"
        "# Do not edit by hand; rerun the script after changing a runbook.\n"
    )
    return header + yaml.safe_dump(
        document, sort_keys=False, allow_unicode=True, width=1000
    )


def main() -> int:
    OUTPUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
